namespace Timbn.GraveyardKeeperTwo.Core.Framework;

/// <summary>The six days of the game's week, named as the game names them.</summary>
public enum TimbnWeekday
{
    /// <summary>The first day of the week.</summary>
    Gluttony,

    /// <summary>The second day, when battles are on.</summary>
    Sloth,

    /// <summary>The third day, when the merchant ship docks.</summary>
    Lust,

    /// <summary>The fourth day, with the storm.</summary>
    Envy,

    /// <summary>The fifth day, when the town vendors take new orders.</summary>
    Pride,

    /// <summary>The sixth and last day, when sermons are held.</summary>
    Wrath,
}
